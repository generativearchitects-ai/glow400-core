#!/usr/bin/env bash
# Regenerates AUTHORS from the git history: one line per distinct author name, in order of first
# commit. Names only; no email addresses are written. Identities are merged through .mailmap.
# Commits by bots (name ending in "[bot]") are skipped.
#
# Usage: scripts/update-authors.sh        (run from anywhere inside the repository)
set -euo pipefail

cd "$(git rev-parse --show-toplevel)"

{
  echo "# The glow400-core authors"
  echo "#"
  echo "# Generated by scripts/update-authors.sh from the git history: do not edit by hand."
  echo "# To merge two identities of the same person, add a line to .mailmap."
  echo
  git log --reverse --use-mailmap --format='%aN' \
    | grep -v '\[bot\]$' \
    | awk '!seen[$0]++'
} > AUTHORS.tmp
mv AUTHORS.tmp AUTHORS
